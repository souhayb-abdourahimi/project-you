/**
 * Workout Coach foundation (W-1, docs/TRAINING_ARCHITECTURE.md §2, D-031): published program
 * versions and immutable prescriptions, so "what was planned" is never recomputed from the current
 * profile. Pure functions: ids and timestamps come from the caller.
 *
 * Kinds of data (D-031 B), never mixed:
 * - FACT: recorded directly (sets done, loads, reps, completion time);
 * - USER_REPORTED: declared by the user (difficulty, reasons, notes, fatigue);
 * - DERIVED: computed and recomputable (gap planned/actual, trends, records), never stored;
 * - RECOMMENDATION: produced by the engine (program versions, prescriptions, proposed loads).
 */

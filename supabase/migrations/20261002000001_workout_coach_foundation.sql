-- ---------------------------------------------------------------------------
-- 6. RLS for the new tables (owner only, nothing for anon)
-- ---------------------------------------------------------------------------

do $$
declare
  t text;
begin
  foreach t in array array['training_programs', 'planned_exercises'] loop
    execute format('create trigger set_updated_at before update on public.%I for each row execute function public.set_updated_at()', t);
    execute format('alter table public.%I enable row level security', t);
    execute format('create policy %I on public.%I for select to authenticated using ((select auth.uid()) = user_id)', t || '_select_own', t);
    execute format('create policy %I on public.%I for insert to authenticated with check ((select auth.uid()) = user_id)', t || '_insert_own', t);
    execute format('create policy %I on public.%I for update to authenticated using ((select auth.uid()) = user_id) with check ((select auth.uid()) = user_id)', t || '_update_own', t);
    execute format('create policy %I on public.%I for delete to authenticated using ((select auth.uid()) = user_id)', t || '_delete_own', t);
    execute format('revoke all on public.%I from anon', t);
    execute format('grant select, insert, update, delete on public.%I to authenticated', t);
  end loop;
end;
$$;

-- ---------------------------------------------------------------------------
-- 7. History recorded before W-1: attach it to a "reconstructed" program
-- ---------------------------------------------------------------------------
-- Idempotent and safe to call from every device: one reconstructed program per user (unique
-- index), sessions attached once. Nothing is invented: the program has no parameters and the
-- sessions get prescription_source = 'unknown' and no planned_exercises. Their sets, outcomes and
-- replacements are kept as they are. Runs with the caller's rights (RLS applies).
create or replace function public.attach_reconstructed_training_history() returns uuid
language plpgsql security invoker set search_path = '' as $$
declare
  uid uuid := (select auth.uid());
  program uuid;
  first_day date;
begin
  if uid is null then
    raise exception 'not authenticated' using errcode = 'insufficient_privilege';
  end if;

  select min(coalesce(s.scheduled_for, s.created_at::date)) into first_day
  from public.workout_sessions s
  where s.user_id = uid and s.program_id is null and s.prescription_source is null and s.deleted_at is null;

  select p.id into program from public.training_programs p where p.user_id = uid and p.source = 'reconstructed';
  if first_day is null then
    return program;
  end if;

  if program is null then
    insert into public.training_programs (user_id, lineage_id, version, source, status, reason_key, effective_from)
    values (uid, gen_random_uuid(), 1, 'reconstructed', 'ended', 'program.reason.reconstructed', first_day)
    on conflict (user_id) where source = 'reconstructed' do nothing
    returning id into program;
    if program is null then
      select p.id into program from public.training_programs p where p.user_id = uid and p.source = 'reconstructed';
    end if;
  end if;

  update public.workout_sessions s
  set program_id = program, prescription_source = 'unknown'
  where s.user_id = uid and s.program_id is null and s.prescription_source is null;

  return program;
end;
$$;

revoke all on function public.attach_reconstructed_training_history() from public, anon;
grant execute on function public.attach_reconstructed_training_history() to authenticated;
